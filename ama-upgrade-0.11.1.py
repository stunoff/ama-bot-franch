CHECKSUM = "b21275d450f4ca10fbceea9f9d3cafca70b6926ff61df93fdbb10c4c76463dc5"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--check', action='store_true', help='validate only, write nothing')
    group.add_argument('--apply', action='store_true', help='back up and update source files')
    args = parser.parse_args()
    root = Path.cwd().resolve()
    if not (root/'ama/bot.py').is_file() or not (root/'alembic.ini').is_file():
        raise SystemExit('Run from the existing project root (where ama/ and compose.yaml are located).')
    packed = base64.b64decode(PAYLOAD)
    if hashlib.sha256(packed).hexdigest() != CHECKSUM:
        raise SystemExit('Transfer checksum mismatch; do not apply this file.')
    data = json.loads(lzma.decompress(packed))
    changes, conflicts = {}, []
    for name, record in data.items():
        path = root/name
        if Path(name).is_absolute() or '..' in Path(name).parts or root not in path.resolve().parents or any(p.is_symlink() for p in [path,*path.parents] if p != root):
            conflicts.append(name+' (unsafe path/symlink)')
            continue
        content = record['content'].encode('utf-8')
        if hashlib.sha256(content).hexdigest() != record['new']:
            raise SystemExit('Content checksum mismatch: '+name)
        current = path.read_bytes() if path.is_file() else None
        digest = hashlib.sha256(current).hexdigest() if current is not None else None
        if digest == record['new']:
            continue
        if digest not in record['old']:
            conflicts.append(name)
        else:
            changes[name] = (current, content)
    if conflicts:
        raise SystemExit('Local changes detected; nothing written. Compare these files first:\n'+'\n'.join(conflicts))
    print('Verified. Files to update:',len(changes))
    if not args.apply or not changes:
        return
    backup = root/'backups'/('source-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'-'+uuid.uuid4().hex[:8])
    if root not in backup.resolve().parents:
        raise SystemExit('Unsafe backup path.')
    backup.mkdir(parents=True, exist_ok=False)
    for name,(current,content) in changes.items():
        if current is not None:
            path = backup/name
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(current)
    (backup/'manifest.json').write_text(json.dumps({'updated':list(changes),'added':[n for n,v in changes.items() if v[0] is None]},ensure_ascii=False,indent=2),encoding='utf-8')
    written=[]
    try:
        for name,(current,content) in changes.items():
            path = root/name
            path.parent.mkdir(parents=True,exist_ok=True)
            temporary = path.with_name(path.name+'.ama-'+uuid.uuid4().hex)
            try:
                temporary.write_bytes(content)
                temporary.chmod(path.stat().st_mode & 0o777 if path.exists() else 0o644)
                os.replace(temporary,path)
                written.append(name)
            finally:
                temporary.unlink(missing_ok=True)
    except BaseException:
        for name in reversed(written):
            path = root/name
            current=changes[name][0]
            if current is None:
                path.unlink(missing_ok=True)
            else:
                path.write_bytes(current)
        raise
    print('Source updated. Previous source saved to',backup)
    print('Database and Docker are unchanged. Follow docs/UPGRADE-0.11.0.md to build, migrate and restart.')


if __name__ == '__main__':
    main()
